const STORAGE_KEY = 'lpf.lang';
const I18nContext = createContext(null);

function detectLanguage() {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (saved && STRINGS[saved]) return saved;
  const browser = (navigator.language || 'en').slice(0, 2).toLowerCase();
  return STRINGS[browser] ? browser : 'en';
}

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(detectLanguage);

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, lang);
    // Screen readers and hyphenation both key off this.
    document.documentElement.lang = lang;
  }, [lang]);

  // Falling back to English rather than showing a raw key means a missing
  // translation degrades to readable text instead of "gallery.useThis".
  const t = useCallback((key) => STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key, [lang]);

  const value = useMemo(() => ({ lang, setLang, t }), [lang, t]);
  return React.createElement(I18nContext.Provider, { value }, children);
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}

